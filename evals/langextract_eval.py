"""Score LangExtract output against the hand-labelled gold set.

Runs the canonical pipeline.langextract_examples.extract on each fixture, flattens
the grounded entities into comparable scalar fields, and scores them against
evals/langextract_gold.py with lenient normalisation (case/space-insensitive,
substring-tolerant for names/places; exact for money). Prints per-notice scores,
an overall accuracy, and — most usefully — the list of MISSES so each prompt/
example change can be judged by the number instead of eyeballing HTML.

Run:  python -m evals.langextract_eval        (needs GOOGLE_API_KEY / LANGEXTRACT_API_KEY)
"""
from __future__ import annotations

import collections
import os
from pathlib import Path

from evals.langextract_gold import EXPECT_NULL, GOLD


def extract_robust(md: str, tries: int = 3, *, model_id: str | None = None,
                   reasoning_off: bool = False,
                   expected_lot_count: int | None = None,
                   roster: list[dict] | None = None):
    """LangExtract occasionally returns 0 extractions (transient empty Gemini
    response) when passes=1. Retry until non-empty so one flaky call doesn't
    tank a whole notice's score.

    ``expected_lot_count`` / ``roster`` are the per-notice prompt context
    production sends (see langextract_examples.prompt_description_for). They
    must be passed here too: an eval that withholds them measures a prompt
    nothing actually runs, so any gain from the lot count or the portal roster
    would be invisible to the score. Callers get them from
    :func:`load_notice_context`.

    `langextract` lives in config/requirements.txt (local/offline), NOT the
    production requirements CI installs — so import it lazily here, keeping the
    pure scoring logic (flatten_records / load_gold / score_notice) importable
    without the dep (the eval gold-wiring tests rely on this)."""
    from pipeline import langextract_examples as LX
    res = None
    for _ in range(tries):
        res = LX.extract(md, model_id=model_id, reasoning_off=reasoning_off,
                         expected_lot_count=expected_lot_count, roster=roster)
        if res.extractions:
            return res
    return res

FIX = Path(__file__).resolve().parent / "fixtures"
# Per-notice prompt context (expected_lot_count + portal roster) for each gold
# notice, captured from the graph by evals/refresh_notice_context.py. A checked-in
# fixture rather than a live query on purpose: the eval has to run offline and
# score the same thing twice, which a query against a moving graph cannot do.
NOTICE_CONTEXT = FIX / "notice_context.json"
# Reviewer-verified gold, generated by evals/export_review_gold.py from the
# extraction-review UI. Loaded alongside the hand-labelled seed so every human
# review hardens the gate.
REVIEWED_GOLD = Path(__file__).resolve().parent / "langextract_gold_reviewed.json"


def load_notice_context() -> dict[str, dict]:
    """{aid: {expected_lot_count, roster}} for the gold notices.

    Missing or unreadable file -> {} , which degrades to the old
    context-free behaviour rather than failing the run.
    """
    import json
    try:
        obj = json.loads(NOTICE_CONTEXT.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return obj if isinstance(obj, dict) else {}


def load_gold() -> list[dict]:
    """Seed gold + reviewer-verified gold (deduped by aid; reviewed wins)."""
    import json
    gold = {g["aid"]: g for g in GOLD}
    if REVIEWED_GOLD.exists():
        try:
            for g in json.loads(REVIEWED_GOLD.read_text(encoding="utf-8")):
                gold[g["aid"]] = g          # human-verified overrides seed
        except (json.JSONDecodeError, OSError):
            pass
    return list(gold.values())
_SC_KEYS = ("legal_basis", "bank_name", "assignor_bank", "trust_name",
            "court_reference")
_LOC_KEYS = ("village", "taluk", "district", "registration_district",
             "registration_sub_district", "hobli")


def _records(res) -> list[dict]:
    """Normalise a live LangExtract result into plain dicts."""
    return [{"cls": e.extraction_class, "text": e.extraction_text,
             "attrs": e.attributes or {}} for e in res.extractions]


def flatten_records(records: list[dict]) -> dict:
    """Collapse normalised entity records into one comparable field dict.

    Shared by the live eval (flatten) and the review-gold exporter
    (evals/export_review_gold.py), so a verified extraction and a fresh one are
    flattened identically.
    """
    out: dict = {"identifiers": collections.defaultdict(set)}
    locs, props, terms, borrowers = [], [], [], []
    for r in records:
        a = r.get("attrs") or {}
        c = r.get("cls")
        text = r.get("text", "")
        if c == "secured_creditor":
            for k in _SC_KEYS:
                if a.get(k):
                    out.setdefault(k, a[k])
            if "bank_name" not in out and a.get("normalized_name"):
                out["bank_name"] = a["normalized_name"]
        elif c == "location":
            locs.append(a)
        elif c == "property":
            props.append(a)
        elif c == "auction_terms":
            terms.append(a)
        elif c == "borrower":
            borrowers.append((a.get("lot_index"), text))
        elif c == "identifier" and a.get("kind") and a.get("value"):
            # Same kind-normalization the loader applies (pipeline/validators),
            # so the eval measures post-normalization reality.
            from pipeline.validators import normalize_identifier_kind
            kind, _ = normalize_identifier_kind(a["kind"])
            out["identifiers"][kind].add(str(a["value"]))

    def _lot1(items):
        return next((i for i in items if i.get("lot_index") in ("1", None)),
                    items[0] if items else {})

    lot1_locs = [lc for lc in locs if lc.get("lot_index") in ("1", None)] or locs
    for k in _LOC_KEYS:
        for loc in lot1_locs:
            if loc.get(k):
                out[k] = loc[k]
                break
    if _lot1(props).get("possession_type"):
        out["possession_type"] = _lot1(props)["possession_type"]
    out["reserve_set"] = {float(t["reserve_price_num"]) for t in terms
                          if t.get("reserve_price_num")}
    out["emd_set"] = {float(t["emd_num"]) for t in terms if t.get("emd_num")}
    # lot_index arrives as whatever the model emitted — "2" from one call, 2 from
    # the next — and sorting a mixed list raises TypeError, killing the whole eval
    # run over one numeric attribute. Coerce before comparing (group_by_lot below
    # already does the same).
    b1 = sorted(borrowers, key=lambda x: str(x[0] if x[0] is not None else "1"))
    out["borrower_primary"] = b1[0][1] if b1 else None
    return out


def flatten(res) -> dict:
    """Collapse a live LangExtract result into one comparable field dict."""
    return flatten_records(_records(res))


def _norm(s) -> str:
    return "".join(ch for ch in str(s).lower() if ch.isalnum())


def _smatch(gold, got) -> bool:
    if got is None:
        return False
    g, h = _norm(gold), _norm(got)
    return bool(g) and (g == h or g in h or h in g)


def score_notice(g: dict, flat: dict) -> list[tuple]:
    rows = []
    for key, gold in g["fields"].items():
        if gold is None:
            continue
        if gold is EXPECT_NULL:
            got = flat.get(key)
            rows.append((key, "<null>", got, got is None))
            continue
        if key == "reserve_price_num":
            got = sorted(flat.get("reserve_set", set()))
            ok = float(gold) in flat.get("reserve_set", set())
        elif key == "emd_num":
            got = sorted(flat.get("emd_set", set()))
            ok = float(gold) in flat.get("emd_set", set())
        else:
            got = flat.get(key)
            ok = _smatch(gold, got)
        rows.append((key, gold, got, ok))
    for kind, val in g.get("identifiers", {}).items():
        got = sorted(flat["identifiers"].get(kind, set()))
        ok = any(_smatch(val, x) for x in got)
        rows.append((f"id:{kind}", val, got, ok))
    return rows


# ── per-lot (multi-notice) scoring ────────────────────────────────────────────
# Multi-lot quality can't be judged by the notice-level flatten (which collapses
# every lot's reserve into ONE set and reads location/possession from lot 1). A
# gold entry may carry a `lots` list — the per-lot truth, labelled against the
# MARKDOWN (every lot present in the text), never the AuctionProperty count. The
# scorer groups the extraction by lot_index, then matches each gold lot to an
# extracted group by RESERVE PRICE (the one anchor that survives OCR-mangled
# serials and per-branch numbering resets) — never by the model's own lot_index,
# which is exactly what breaks. This measures whether each field is bound to the
# RIGHT lot, plus whether the lot COUNT is correct.
_LOC_SETS = (("village", "villages"), ("taluk", "taluks"),
             ("district", "districts"),
             ("registration_district", "reg_districts"),
             ("registration_sub_district", "reg_subs"))
# Classes that describe the notice as a whole, not one lot — never binned.
_NOTICE_CLASSES = frozenset({"secured_creditor", "emd_account", "full_terms",
                             "contact"})


def _fnum(v):
    try:
        return float(str(v).replace(",", "").strip())
    except (TypeError, ValueError):
        return None


def group_by_lot(records: list[dict]) -> list[dict]:
    """Bucket extracted entities into lots keyed by their lot_index.

    Returns one dict per distinct lot_index seen on a per-lot entity, each
    aggregating that lot's reserves/emds (sets), location values (sets), and
    identifiers ({kind: set}). Notice-level classes are dropped; an entity with
    no lot_index falls into bucket "1" (so a model that emits everything
    unnumbered collapses to a single lot — correctly flagged as under-count).
    """
    from pipeline.validators import normalize_identifier_kind  # lazy (offline dep)
    groups: dict[str, dict] = {}

    def bucket(li: str) -> dict:
        return groups.setdefault(li, {
            "lot_index": li, "reserves": set(), "emds": set(), "villages": set(),
            "taluks": set(), "districts": set(), "reg_districts": set(),
            "reg_subs": set(), "identifiers": collections.defaultdict(set)})

    for r in records:
        c = r.get("cls")
        if c in _NOTICE_CLASSES:
            continue
        a = r.get("attrs") or {}
        grp = bucket(str(a.get("lot_index") or "1"))
        if c == "auction_terms":
            rp, em = _fnum(a.get("reserve_price_num")), _fnum(a.get("emd_num"))
            if rp is not None:
                grp["reserves"].add(rp)
            if em is not None:
                grp["emds"].add(em)
        elif c == "location":
            for key, setk in _LOC_SETS:
                if a.get(key):
                    grp[setk].add(a[key])
        elif c == "identifier" and a.get("kind") and a.get("value") not in (None, ""):
            kind, _ = normalize_identifier_kind(a["kind"])
            grp["identifiers"][kind].add(str(a["value"]))
    return list(groups.values())


def _match_group(lot: dict, groups: list[dict], used: set) -> tuple:
    """Find the extracted group for a gold lot: reserve price first, then (when
    several lots share a reserve — e.g. two identical flats) an identifier
    tiebreak. Returns (group_or_None, index_or_None)."""
    res = _fnum(lot.get("reserve_price_num"))
    cands = [(i, g) for i, g in enumerate(groups)
             if i not in used and res is not None and res in g["reserves"]]
    if not cands:
        return None, None
    if len(cands) == 1:
        return cands[0][1], cands[0][0]
    for i, g in cands:  # disambiguate on any labelled identifier
        for kind, val in (lot.get("identifiers") or {}).items():
            if any(_smatch(val, x) for x in g["identifiers"].get(kind, ())):
                return g, i
    return cands[0][1], cands[0][0]


def _score_lot(tag: str, lot: dict, grp: dict | None) -> list[tuple]:
    rows = []
    res = _fnum(lot.get("reserve_price_num"))
    rows.append((f"{tag}:reserve", res,
                 sorted(grp["reserves"]) if grp else None,
                 bool(grp) and res in grp["reserves"]))
    if grp is None:  # unmatched lot — every labelled field misses
        if lot.get("emd_num") is not None:
            rows.append((f"{tag}:emd", _fnum(lot["emd_num"]), None, False))
        for key, _ in _LOC_SETS:
            if lot.get(key):
                rows.append((f"{tag}:{key}", lot[key], None, False))
        for kind, val in (lot.get("identifiers") or {}).items():
            rows.append((f"{tag}:id:{kind}", val, None, False))
        return rows
    if lot.get("emd_num") is not None:
        em = _fnum(lot["emd_num"])
        rows.append((f"{tag}:emd", em, sorted(grp["emds"]), em in grp["emds"]))
    for key, setk in _LOC_SETS:
        if lot.get(key):
            got = sorted(grp[setk])
            rows.append((f"{tag}:{key}", lot[key], got,
                         any(_smatch(lot[key], x) for x in grp[setk])))
    for kind, val in (lot.get("identifiers") or {}).items():
        got = sorted(grp["identifiers"].get(kind, ()))
        rows.append((f"{tag}:id:{kind}", val, got,
                     any(_smatch(val, x) for x in got)))
    return rows


def score_multi(g: dict, records: list[dict]) -> tuple:
    """Per-lot scoring. Returns (rows, (n_gold_lots, n_extracted_lots, count_ok)).

    An extracted "lot" is a group carrying a reserve price (the auction unit).
    Each gold lot is matched by reserve price + identifier tiebreak; its fields
    are scored against the matched group so a field bound to the WRONG lot fails.
    """
    groups = group_by_lot(records)
    lot_groups = [gr for gr in groups if gr["reserves"]]
    rows: list[tuple] = []
    used: set = set()
    for i, lot in enumerate(g["lots"], start=1):
        grp, gi = _match_group(lot, lot_groups, used)
        if gi is not None:
            used.add(gi)
        rows.extend(_score_lot(f"lot{i}", lot, grp))
    n_gold, n_got = len(g["lots"]), len(lot_groups)
    count_ok = n_got == n_gold
    rows.append(("lot_count", n_gold, n_got, count_ok))
    return rows, (n_gold, n_got, count_ok)


def score_records(g: dict, records: list[dict]) -> tuple:
    """Score one notice from its extracted records. Returns (rows, lot_stats);
    lot_stats is None for single notices, else (n_gold, n_got, count_ok)."""
    rows = score_notice(g, flatten_records(records))
    lot_stats = None
    if g.get("lots"):
        lrows, lot_stats = score_multi(g, records)
        rows = rows + lrows
    return rows, lot_stats


def main() -> int:
    os.environ.setdefault("LANGEXTRACT_API_KEY",
                          os.environ.get("GOOGLE_API_KEY", ""))
    os.environ.setdefault("LANGEXTRACT_PASSES", "1")
    from pipeline.validators import full_description_coverage
    total = correct = 0
    misses = []
    multi_stats = []   # (aid, n_gold_lots, n_extracted_lots, count_ok)
    fd_incomplete = []   # aids where full_description didn't cover all detail
    gold = load_gold()
    ctx = load_notice_context()
    print(f"LangExtract eval — {len(gold)} notices "
          f"({len(GOLD)} seed + {len(gold) - len(GOLD)} reviewer-verified, "
          f"passes={os.environ['LANGEXTRACT_PASSES']}, "
          f"context for {sum(1 for g in gold if g['aid'] in ctx)}/{len(gold)})\n")
    for g in gold:
        md = (FIX / f"{g['aid']}.txt").read_text(encoding="utf-8")
        c = ctx.get(g["aid"]) or {}
        res = extract_robust(md,
                             expected_lot_count=c.get("expected_lot_count"),
                             roster=c.get("roster"))
        records = _records(res)
        rows, lot_stats = score_records(g, records)
        c = sum(1 for *_, ok in rows if ok)
        total += len(rows)
        correct += c
        lot_note = ""
        if lot_stats is not None:
            n_gold, n_got, count_ok = lot_stats
            multi_stats.append((g["aid"], n_gold, n_got, count_ok))
            lot_note = f"  lots={n_got}/{n_gold}{'' if count_ok else ' ⚠'}"
        # source-of-truth check: does full_description cover every descriptive span?
        cov = full_description_coverage(res.extractions)
        fd_note = ""
        if cov["lots_incomplete"] or cov["lots_missing_full_description"]:
            fd_incomplete.append((g["aid"], cov))
            fd_note = "  fd⚠"
        print(f"  {g['aid']} ({g['notice_type']:6}): {c}/{len(rows)}{lot_note}{fd_note}")
        misses += [(g["aid"], k, gd, got) for k, gd, got, ok in rows if not ok]
    print(f"\nOVERALL ACCURACY: {correct}/{total} = {correct/total*100:.1f}%")
    complete = len(gold) - len(fd_incomplete)
    print(f"FULL_DESCRIPTION complete (covers all descriptive spans): "
          f"{complete}/{len(gold)}")
    for aid, cov in fd_incomplete:
        bits = []
        if cov["lots_missing_full_description"]:
            bits.append(f"missing on lot(s) {cov['lots_missing_full_description']}")
        if cov["lots_incomplete"]:
            bits.append("outside: " + ", ".join(
                f"lot {li} {cls}" for li, cls in cov["lots_incomplete"].items()))
        print(f"  {aid}: {'; '.join(bits)}")
    if multi_stats:
        lc_ok = sum(1 for *_, ok in multi_stats if ok)
        print(f"\nMULTI-LOT lot-count: {lc_ok}/{len(multi_stats)} notices correct")
        for aid, n_gold, n_got, count_ok in multi_stats:
            print(f"  {aid}: gold={n_gold} extracted={n_got} "
                  f"{'OK' if count_ok else 'MISMATCH'}")
    if misses:
        print("\nMISSES (auction_id  field  gold -> got):")
        for aid, key, gd, got in misses:
            print(f"  {aid}  {key:26} {gd!r:24} -> {got!r}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
